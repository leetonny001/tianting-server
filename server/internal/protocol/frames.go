// NullableMs 把"到期时间，永久为 null"编码成字段值：用于只在特定情况出现、出现时可以是 null 的字段。
func NullableMs(ms *int64) json.RawMessage {
	if ms == nil {
		return json.RawMessage("null")
	}
	return json.RawMessage(strconv.FormatInt(*ms, 10))
}

