const (
	MaxTextLen       = 5000 // 按码点计，去首尾空白之后
	defaultSyncLimit = 50
	maxSyncLimit     = 200
	lastMsgTextLen   = 100
)

var idPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{1,64}$`)

// ValidID 判断用户 / 群 / 房间 ID 是否合法。
func ValidID(s string) bool { return idPattern.MatchString(s) }

// TrimText 去掉首尾空白。空白以 Unicode White_Space 属性为准（unicode.IsSpace），
// U+200B、U+FEFF 不算空白（PRD C-26）。
func TrimText(s string) string { return strings.TrimFunc(s, unicode.IsSpace) }

// TextLen 按 Unicode 码点计数（PRD 3.1 节）。
func TextLen(s string) int { return utf8.RuneCountInString(s) }

// Error 是 ack 里的错误，同时实现 error 接口，便于在业务层直接返回。
type Error struct {
	Code int    `json:"code"`
	Msg  string `json:"msg"`
	// UserID 指出是哪个人（建群失败，PRD-social 9.2 节）；没有时不出现。
	UserID string `json:"userId,omitempty"`
	// Reason 细分同一个错误码（4030 的 c2cBodyDisabled，PRD-admin 10.3 节）。
	Reason string `json:"reason,omitempty"`
	// Details 是可选扩展（4031 的 {scope, groupId?, mutedUntil}，4034 的 {bannedUntil}，PRD-admin 11.1 节）。SDK 忽略不认识的键。
	Details map[string]any `json:"details,omitempty"`
}

func (e *Error) Error() string { return fmt.Sprintf("%d %s", e.Code, e.Msg) }

// Errorf 构造协议错误。
func Errorf(code int, format string, args ...any) *Error {
	return &Error{Code: code, Msg: fmt.Sprintf(format, args...)}
}

// InFrame 是客户端上行帧，data 延迟到具体命令再解析。
type InFrame struct {
	ID   string          `json:"id,omitempty"`
	Cmd  string          `json:"cmd"`
	Data json.RawMessage `json:"data,omitempty"`
}

// OutFrame 是服务端下行帧。
type OutFrame struct {
	ID    string `json:"id,omitempty"`
	Cmd   string `json:"cmd"`
	Data  any    `json:"data,omitempty"`
	Error *Error `json:"error,omitempty"`
}

// AckOK / AckErr 构造对请求的应答。
func AckOK(id string, data any) OutFrame { return OutFrame{ID: id, Cmd: CmdAck, Data: data} }
func AckErr(id string, err *Error) OutFrame {
	return OutFrame{ID: id, Cmd: CmdAck, Error: err}
}

// Event 构造事件帧。
func Event(data any) OutFrame { return OutFrame{Cmd: CmdEvent, Data: data} }

// MsgBody 是消息内容：text 消息用 Text，custom 消息用 Data。
type MsgBody struct {
	Text string          `json:"text,omitempty"`
	Data json.RawMessage `json:"data,omitempty"`
	Tip  *TipBody        `json:"tip,omitempty"`
}

// TipBody 是群提示消息的内容（F-SOC-29 规则 2）。actor 为空表示系统操作；targets 最多 20 个，超过时带 count。
type TipBody struct {
	Kind    string   `json:"kind"`
	Actor   string   `json:"actor"`
	Targets []string `json:"targets"`
	Count   int      `json:"count,omitempty"`
	Text    string   `json:"text"`
}

// Message 是下行的一条消息（msg 帧、sync 结果里都用它）。
type Message struct {
	MsgID       string  `json:"msgId"`
	ClientMsgID string  `json:"clientMsgId"`
	ConvID      string  `json:"convId"`
	Seq         int64   `json:"seq,omitempty"`
	From        string  `json:"from"`
	Type        string  `json:"type"`
	Body        MsgBody `json:"body,omitzero"` // 被删除的消息没有 body（第二批，F-MSG-05 规则 7）
	TS          int64   `json:"ts"`
	Deleted     bool    `json:"deleted,omitempty"`
	DeletedAt   int64   `json:"deletedAt,omitempty"`
}

// SendReq 对应 cmd=send。
type SendReq struct {
	ConvType    string  `json:"convType"`
	To          string  `json:"to"`
	ClientMsgID string  `json:"clientMsgId"`
	Type        string  `json:"type"`
	Body        MsgBody `json:"body"`
}

// Validate 校验并规范化请求：text 消息的内容会被去掉首尾空白。
func (r *SendReq) Validate() *Error {
	switch r.ConvType {
	case ConvC2C, ConvGroup, ConvRoom:
	default:
		return Errorf(CodeBadRequest, "invalid convType %q", r.ConvType)
	}
	if !ValidID(r.To) {
		return Errorf(CodeInvalidID, "invalid to")
	}
	if n := len(r.ClientMsgID); n < 8 || n > 64 {
		return Errorf(CodeBadRequest, "clientMsgId length must be 8-64")
	}
	// tip- 前缀和 body.tip 保留给服务端生成的提示消息（F-SOC-29 规则 1）。
	if strings.HasPrefix(r.ClientMsgID, "tip-") || r.Body.Tip != nil {
		return Errorf(CodeBadRequest, "tip messages are generated by the server")
	}
	switch r.Type {
	case MsgText:
		r.Body.Text = TrimText(r.Body.Text)
		if r.Body.Text == "" {
			return Errorf(CodeTextEmpty, "text is empty")
		}
		if TextLen(r.Body.Text) > MaxTextLen {
			return Errorf(CodeTextTooLong, "text longer than %d", MaxTextLen)
		}
	case MsgCustom:
		if len(r.Body.Data) == 0 || string(r.Body.Data) == "null" {
			return Errorf(CodeBadRequest, "custom body.data is empty")
		}
	default:
		return Errorf(CodeBadRequest, "invalid type %q", r.Type)
	}
	return nil
}

// AuthReq 对应 cmd=auth：连接后的第一帧（PRD C-52）。
type AuthReq struct {
	Token string `json:"token"`
}

// AuthAck 是 auth 成功的应答。
type AuthAck struct {
	UserID     string `json:"userId"`
	ServerTime int64  `json:"serverTime"`
	// MutedUntil 只在用户被用户级禁言时出现，永久禁言为 null（第二批，F-ADM-40 规则 4）。
	MutedUntil json.RawMessage `json:"mutedUntil,omitempty"`
	// RecoveryCodeUnacked 只在账号最新一代恢复码没有确认时出现（PRD-chat F-ACC-05 规则 1）。
	RecoveryCodeUnacked bool `json:"recoveryCodeUnacked,omitempty"`
}

// SendAck 是 send 成功的应答。聊天室消息没有 seq。
type SendAck struct {
	MsgID  string `json:"msgId"`
	ConvID string `json:"convId"`
	Seq    int64  `json:"seq,omitempty"`
	TS     int64  `json:"ts"`
}

// SyncReq 对应 cmd=sync。AfterSeq 与 BeforeSeq 二选一。
type SyncReq struct {
	ConvID    string `json:"convId"`
	AfterSeq  *int64 `json:"afterSeq"`
	BeforeSeq *int64 `json:"beforeSeq"`
	Limit     *int   `json:"limit"`
}

// Validate 校验请求，并返回生效的 limit。
func (r *SyncReq) Validate() (int, *Error) {
	if _, err := ParseConvID(r.ConvID); err != nil {
		return 0, err
	}
	if (r.AfterSeq == nil) == (r.BeforeSeq == nil) {
		return 0, Errorf(CodeBadRequest, "exactly one of afterSeq and beforeSeq is required")
	}
	if r.AfterSeq != nil && *r.AfterSeq < 0 {
		return 0, Errorf(CodeBadRequest, "afterSeq must be >= 0")
	}
	if r.BeforeSeq != nil && *r.BeforeSeq < 1 {
		return 0, Errorf(CodeBadRequest, "beforeSeq must be >= 1")
	}
	limit := defaultSyncLimit
	if r.Limit != nil {
		limit = *r.Limit
	}
	if limit < 1 || limit > maxSyncLimit {
		return 0, Errorf(CodeBadRequest, "limit must be 1-%d", maxSyncLimit)
	}
	return limit, nil
}

// SyncAck 是 sync 的应答，messages 按 seq 升序。
type SyncAck struct {
	Messages []Message `json:"messages"`
	HasMore  bool      `json:"hasMore"`
}

// ReadReq 对应 cmd=read。
type ReadReq struct {
	ConvID string `json:"convId"`
	Seq    int64  `json:"seq"`
}

func (r *ReadReq) Validate() *Error {
	if _, err := ParseConvID(r.ConvID); err != nil {
		return err
	}
	if r.Seq < 1 {
		return Errorf(CodeBadRequest, "seq must be >= 1")
	}
	return nil
}

// LastMsg 是会话最后一条消息的摘要。
type LastMsg struct {
	MsgID string `json:"msgId"`
	From  string `json:"from"`
	Type  string `json:"type"`
	Text  string `json:"text"`
	TS    int64  `json:"ts"`
	// Deleted：最后一条消息被删除（第二批，F-ADM-31 规则 3）；这时 JSON 里没有 text。
	Deleted bool `json:"deleted,omitempty"`
}

// MarshalJSON：被删除的消息不带 text，其他情况 text 一定出现（可以是空字符串）。
func (m LastMsg) MarshalJSON() ([]byte, error) {
	if !m.Deleted {
		type plain LastMsg
		return json.Marshal(plain(m))
	}
	return json.Marshal(struct {
		MsgID   string `json:"msgId"`
		From    string `json:"from"`
		Type    string `json:"type"`
		TS      int64  `json:"ts"`
		Deleted bool   `json:"deleted"`
	}{m.MsgID, m.From, m.Type, m.TS, true})
}

// Summary 截取消息摘要（前 100 个码点）。
func Summary(text string) string {
	if TextLen(text) <= lastMsgTextLen {
		return text
	}
	r := []rune(text)
	return string(r[:lastMsgTextLen])
}

// Conversation 是会话列表里的一项。
type Conversation struct {
	ConvID    string   `json:"convId"`
	Type      string   `json:"type"`
	Name      string   `json:"name"`
	MaxSeq    int64    `json:"maxSeq"`
	ReadSeq   int64    `json:"readSeq"`
	MinSeq    int64    `json:"minSeq"`
	Unread    int64    `json:"unread"`
	LastMsg   *LastMsg `json:"lastMsg"` // 没有消息时为 null
	UpdatedAt int64    `json:"updatedAt"`
	// MemberCount 是群成员数（PRD-core V-07）；单聊不带这个字段。客户端遇到字段缺失时只显示群名。
	MemberCount *int `json:"memberCount,omitempty"`
	// MyRole 是群里我的角色（M4）：owner / admin / member；单聊不带。
	MyRole string `json:"myRole,omitempty"`
	// MutedUntil：我在该群被禁言时才出现，永久禁言为 null（第二批，F-ADM-41 规则 5）。
	MutedUntil json.RawMessage `json:"mutedUntil,omitempty"`
	// AllMuted：该群开启了全群禁言时才出现（P1，F-ADM-42）。所有成员都带，含不受限的群主、管理员；结合 MyRole 判断自己能否发言。
	AllMuted bool `json:"allMuted,omitempty"`
}

