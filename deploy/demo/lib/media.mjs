import { deflateSync } from 'node:zlib';

const CRC = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

/** RGB 像素（每行 width*3 字节）编码成 PNG。 */
function png(width, height, pixel) {
  const raw = Buffer.alloc((width * 3 + 1) * height);
  let o = 0;
  for (let y = 0; y < height; y++) {
    raw[o++] = 0; // 不做行过滤
    for (let x = 0; x < width; x++) {
      const [r, g, b] = pixel(x / width, y / height);
      raw[o++] = r;
      raw[o++] = g;
      raw[o++] = b;
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // 位深
  ihdr[9] = 2; // RGB
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const mix = (a, b, t) => a.map((v, i) => Math.round(v + (b[i] - v) * t));
const clamp = (t) => Math.max(0, Math.min(1, t));

/** 山景：天空渐变、太阳、两层山、湖面倒影。u、v 是 0～1 的坐标。 */
function mountains(palette) {
  const { skyTop, skyBottom, sun, far, near, lake } = palette;
  return (u, v) => {
    const farLine = 0.52 - 0.12 * Math.sin(u * 7.1 + 0.6) - 0.06 * Math.sin(u * 17.3);
    const nearLine = 0.62 - 0.1 * Math.sin(u * 4.3 + 2.1) - 0.04 * Math.sin(u * 23.7 + 1);
    if (v > 0.74) {
      // 湖面：天空颜色的倒影加一点波纹
      const t = clamp((v - 0.74) / 0.26);
      const ripple = 0.04 * Math.sin(v * 180 + u * 9);
      return mix(mix(skyBottom, lake, 0.55), lake, clamp(t + ripple));
    }
    if (v > nearLine) return mix(near, [20, 30, 40], clamp((v - nearLine) * 2));
    if (v > farLine) return mix(far, near, clamp((v - farLine) * 1.5));
    const dx = (u - 0.7) * 1.5;
    const dy = v - 0.3;
    const d = Math.sqrt(dx * dx + dy * dy);
    if (d < 0.07) return sun;
    const glow = clamp(1 - (d - 0.07) / 0.25) * 0.35;
    return mix(mix(skyTop, skyBottom, clamp(v / 0.62)), sun, glow);
  };
}

const PALETTES = {
  dusk: {
    skyTop: [58, 72, 160],
    skyBottom: [250, 170, 120],
    sun: [255, 236, 180],
    far: [110, 96, 150],
    near: [52, 60, 98],
    lake: [70, 90, 150],
  },
  morning: {
    skyTop: [90, 160, 230],
    skyBottom: [210, 236, 250],
    sun: [255, 250, 220],
    far: [120, 170, 150],
    near: [50, 120, 90],
    lake: [80, 150, 190],
  },
};

/** 图片消息：原图和缩略图（长边 ≤ 480）。 */
export function landscape(name, width = 1200, height = 800) {
  const draw = mountains(PALETTES[name]);
  const scale = 480 / Math.max(width, height);
  const tw = Math.round(width * scale);
  const th = Math.round(height * scale);
  return {
    original: { data: new Uint8Array(png(width, height, draw)), mime: 'image/png' },
    thumb: { data: new Uint8Array(png(tw, th, draw)), mime: 'image/png' },
    width,
    height,
  };
}

/** 一页的 PDF（只用 ASCII 文字和内置字体，不嵌入任何字体文件）。 */
export function agendaPdf() {
  const lines = [
    'Tianting demo agenda',
    '',
    '1. Send a message on H5, receive it on the phones',
    '2. Recall, quote, @ and @all',
    '3. Pin a conversation, turn notifications off',
    '4. A blocked word is rejected',
    '5. Report a message, handle it in the admin console',
    '',
    'Generated by deploy/demo/lib/media.mjs for the local demo.',
  ];
  const esc = (s) => s.replace(/[\\()]/g, (c) => '\\' + c);
  const text = ['BT', '/F1 16 Tf', '20 TL', '72 760 Td', ...lines.map((l) => `(${esc(l)}) '`), 'ET'].join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(text)} >>\nstream\n${text}\nendstream`,
  ];
  let out = '%PDF-1.4\n';
  const offsets = [];
  objs.forEach((o, i) => {
    offsets.push(Buffer.byteLength(out));
    out += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n`;
  for (const off of offsets) out += `${String(off).padStart(10, '0')} 00000 n \n`;
  out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return new Uint8Array(Buffer.from(out, 'latin1'));
}
